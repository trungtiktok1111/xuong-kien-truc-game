from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
    pg=b.new_page(viewport={'width':390,'height':800});errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.on('dialog',lambda d:d.accept('16'))
    pg.goto('file:///home/claude/ed/index.html');pg.wait_for_timeout(800)
    clk=lambda t:pg.evaluate("t=>[...document.querySelectorAll('button')].find(b=>b.textContent.includes(t)).click()",t)
    clk('Tileset');pg.wait_for_timeout(300)
    with pg.expect_file_chooser() as fc: clk('Nạp gói')
    fc.value.set_files('/tmp/zt/pack.zip');pg.wait_for_timeout(800)
    pg.screenshot(path='z1.png')
    pg.evaluate("[...document.querySelectorAll('div')].find(d=>d.textContent==='Kenney/tiles/t.png').click()");pg.wait_for_timeout(500)
